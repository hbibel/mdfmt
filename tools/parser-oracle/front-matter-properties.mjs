import assert from "node:assert/strict";
import {createHash} from "node:crypto";
import {readFileSync,writeFileSync} from "node:fs";
import {RE2JS} from "re2js";

const base = new URL("node_modules/re2js/", import.meta.url);
assert.equal(JSON.parse(readFileSync(new URL("package.json",base))).version,"2.8.6");
const source = readFileSync(new URL("build/index.js",base),"utf8");
const categories = source.slice(source.indexOf("static CATEGORIES ="),source.indexOf("static get Upper()"));
const names = [...categories.matchAll(/^\s+(\w+):/gm)].map(match=>match[1]).concat("Any","Assigned");
const rows=[];
for(const name of names) {
    const pattern = new RegExp(`\\p{${name}}`,"u");
    const compiled = RE2JS.compile(RE2JS.translateRegExp(pattern));
    const classes = compiled.re2Input.prog.inst.filter(inst=>inst.runes.length);
    assert.equal(classes.length,1,name);
    const instruction=classes[0];
    assert.ok([8,9,10].includes(instruction.op),name);
    const endpoints=instruction.op===9?[instruction.runes[0],instruction.runes[0]]:instruction.runes;
    assert.equal(endpoints.length%2,0,name);
    let body="";
    for(let index=0;index<endpoints.length;index+=2) {
        const first=endpoints[index],last=endpoints[index+1];
        for(const [lower,upper] of [[0,0xd7ff],[0xe000,0x10ffff]]) {
            const start=Math.max(first,lower),end=Math.min(last,upper);
            if(start<=end)body+=`\\x{${start.toString(16)}}`+(start===end?"":`-\\x{${end.toString(16)}}`);
        }
    }
    rows.push(`        "${name}" => Some(r"[${body||"a&&b"}]"),`);
}
const digest=createHash("sha256").update(source).digest("hex");
const output=`// Generated by tools/parser-oracle/front-matter-properties.mjs from RE2JS 2.8.6.
// Pinned build/index.js SHA-256: ${digest}
// Surrogates are excluded because source text is UTF-8. See RE2JS-LICENSE.txt.
pub(super) fn class(name: &str) -> Option<&'static str> {
    match name {
${rows.join("\n")}
        _ => None,
    }
}
`;
const destination=new URL("../../src/config/front_matter_properties.rs",import.meta.url);
if(process.argv.includes("--record"))writeFileSync(destination,output);
else assert.equal(readFileSync(destination,"utf8"),output);
console.log(`PASS: ${rows.length} pinned RE2JS Unicode property classes (${Buffer.byteLength(output)} bytes)`);
